import { chromium } from "playwright";
import { AxeBuilder } from "@axe-core/playwright";
import { mkdirSync } from "node:fs";
const base = process.argv[2]; const out = process.argv[3];
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true, locale: "en-AU", timezoneId: "Australia/Sydney", colorScheme: "dark" });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const byText = (t) => page.getByText(t, { exact: true }).filter({ visible: true }).first();
const tid = (id) => page.getByTestId(id).filter({ visible: true }).first();
let n = 0;
async function shot(name, full = false) {
  await page.waitForTimeout(700);
  n += 1;
  await page.screenshot({ path: `${out}/${String(n).padStart(2, "0")}-${name}.png`, fullPage: full });
  const axe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze();
  const serious = axe.violations.filter((v) => v.impact === "serious" || v.impact === "critical");
  console.log(`${name}: ${serious.length ? serious.map((v) => `${v.id}(${v.nodes.length})`).join(", ") : "no serious axe issues"}`);
}
await page.goto(base); await page.waitForLoadState("networkidle");
await tid("sample").click();
await byText("Wholesale order for Saturday markets").waitFor();
await page.goto(`${base}/tasks`);
await byText("Chase INV-1042 with Green Roof Cafe").click();
await tid("timer-start").click();
await tid("timer-elapsed").waitFor();
await page.waitForTimeout(4200);
await shot("task-timer-running");
// Back in the app, not a reload: the sample workspace lives in memory.
await page.goBack();
await tid("timer-chip").waitFor();
await shot("tasks-timer-chip");
await page.goto(`${base}/meetings`);
await byText("Kiosk fit out walkthrough").waitFor();
await shot("meetings-list");
console.log("errors:", JSON.stringify(errors.slice(0, 5)));
await browser.close();
