/** The SF Symbol to draw for an icon, or null when there is no mapping. */
export function sfSymbolFor(name: IconName, filled = false): string | null {
  const base = SF_SYMBOLS[name];
  if (!base) return null;
  return filled && !NO_FILL.has(base) ? `${base}.fill` : base;
}
