// Generates src/web/components/ui/icons/: one module per semantic icon name (so each page chunk carries only the
// glyphs it uses), plus src/web/components/ui/icons/index.ts re-exporting them. Phosphor glyphs (MIT) in two weights
// only, regular and fill. The map is scripts/r35-icon-map.json (name -> Phosphor component), kept in step with the
// phone app's scripts/gen-icons.mjs where names are shared.
// Usage: npx tsx scripts/r35-gen-icons.mjs
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as P from "@phosphor-icons/react/dist/ssr";
import fs from "node:fs";

const map = JSON.parse(fs.readFileSync("scripts/r35-icon-map.json", "utf8"));
const dir = "src/web/components/ui/icons";
fs.rmSync(dir, { recursive: true, force: true });
fs.mkdirSync(dir, { recursive: true });
const pascal = (n) => "Icon" + n.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const head = "// Generated by scripts/r35-gen-icons.mjs from Phosphor Icons (MIT, see THIRD_PARTY_NOTICES.md). Do not edit by hand.\n";
const index = [head, "// One module per icon: a chunk only carries the icons it imports.\n"];
for (const name of Object.keys(map).sort()) {
  const C = P[map[name]];
  if (!C) throw new Error(`no Phosphor glyph ${map[name]} for ${name}`);
  const inner = (weight) => renderToStaticMarkup(createElement(C, { weight })).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  fs.writeFileSync(`${dir}/${name}.ts`, `${head}import { makeIcon } from "../icon-base";\n\nexport const ${pascal(name)} = /*#__PURE__*/ makeIcon(${JSON.stringify(name)}, ${JSON.stringify(inner("regular"))}, ${JSON.stringify(inner("fill"))});\n`);
  index.push(`export { ${pascal(name)} } from "./${name}";\n`);
}
fs.writeFileSync(`${dir}/index.ts`, index.join(""));
console.log(`${Object.keys(map).length} icons`);
