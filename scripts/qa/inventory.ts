/**
 * Writes docs/qa/inventory.md: every web route, API endpoint, MCP tool, webhook event,
 * cron job, mobile screen and setting, read from the code so it stays complete.
 *   npx tsx scripts/qa/inventory.ts [path/to/mobile/src/app]
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { openSqlite } from "../../src/server/db/node";
import { migrate } from "../../src/server/db";
import { createApp } from "../../src/server/app";
import { loadConfig } from "../../src/server/config";
import { StaticResolver } from "../../src/server/services/dns/resolver";
import { LogOutbound } from "../../src/server/services/mail/outbound";
import { nullLogger } from "../../src/server/lib/logger";
import { WEBHOOK_EVENTS } from "../../src/server/services/developer/webhooks";
import { v1Routes } from "../../src/server/routes/v1";

const db = openSqlite(":memory:");
await migrate(db);
const app = createApp({ db, config: loadConfig({ APP_SECRET: "x".repeat(40), DEMO_MODE: "true" }), dns: new StaticResolver(), outbound: new LogOutbound(), now: () => new Date(), fetch: fetch, log: nullLogger });

const seen = new Set<string>();
const api: { method: string; path: string }[] = [];
for (const r of [...app.routes, ...v1Routes().routes.map((x) => ({ ...x, path: `/api/v1${x.path === "/" ? "" : x.path}` }))]) {
  if (r.method === "ALL" || !r.path.startsWith("/api") || r.path === "/api/v1/*" || r.path === "/api/v1") continue;
  const key = `${r.method} ${r.path}`;
  if (seen.has(key)) continue;
  seen.add(key);
  api.push({ method: r.method, path: r.path });
}
api.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const group = (p: string) => p.split("/").slice(0, p.startsWith("/api/v1") ? 4 : 3).join("/");

const router = readFileSync("src/web/router.tsx", "utf8");
const SETTINGS = new Set(["team", "billing", "account", "mail", "mail-apps", "developers"]);
const pages = [...router.matchAll(/path: "([^"]+)"/g)].map((m) => m[1])
  .map((p) => (p.startsWith("/") || p === "*" ? p : SETTINGS.has(p) ? `/app/settings/${p}` : `/app/${p}`));
const mcp = [...readFileSync("src/server/routes/mcp-server.ts", "utf8").matchAll(/registerTool\("([a-z_]+)"/g)].map((m) => m[1]);
const crons = [...readFileSync("wrangler.toml", "utf8").matchAll(/crons = \[([^\]]*)\]/g)].map((m) => m[1]);

const mobileDir = process.argv[2] ?? "../mobile/src/app";
const screens: string[] = [];
const walk = (d: string, rel = "") => {
  for (const f of readdirSync(d)) {
    const full = path.join(d, f);
    if (statSync(full).isDirectory()) walk(full, `${rel}/${f}`);
    else if (/\.tsx$/.test(f) && !f.startsWith("_")) screens.push(`${rel}/${f.replace(/\.tsx$/, "")}`.replace(/\/index$/, "/") || "/");
  }
};
if (existsSync(mobileDir)) walk(mobileDir);

const lines: string[] = [];
lines.push("# MyMail feature inventory", "", `Generated by scripts/qa/inventory.ts from the code. ${api.length} API endpoints, ${pages.length} web routes, ${mcp.length} MCP tools, ${WEBHOOK_EVENTS.length} webhook events, ${screens.length} mobile screens.`, "");
lines.push("Results for each item are in docs/qa/report.md.", "");
lines.push("## Web routes", "", ...pages.map((p) => `- \`${p}\``), "");
lines.push("## Settings", "", "- General (`/app/settings`)", ...pages.filter((p) => p.startsWith("/app/settings/")).map((p) => `- ${p.split("/").pop()} (\`${p}\`)`), "");
lines.push("## API endpoints", "");
let last = "";
for (const r of api) {
  const g = group(r.path);
  if (g !== last) { lines.push("", `### ${g}`, ""); last = g; }
  lines.push(`- ${r.method} \`${r.path}\``);
}
lines.push("", "## MCP tools", "", ...mcp.map((t) => `- \`${t}\``), "");
lines.push("## Webhook events (Standard Webhooks)", "", ...WEBHOOK_EVENTS.map((e) => `- \`${e}\``), "");
lines.push("## Inbound webhooks", "", "- Resend delivery events: `POST /api/webhooks/resend`", "- Provider webhooks (Stripe and others): `/api/webhooks/*`", "- Inbound mail from the Cloudflare email worker: `/api/inbound/*`", "");
lines.push("## Cron jobs", "", ...crons.map((c, i) => `- ${i === 0 ? "production" : "staging"}: ${c} runs maintenance (jobs, uptime check, cross checks, legacy clean up, dunning, approval expiry, due date reminders, pruning)`), "");
lines.push("## Mobile screens (Expo Router)", "", ...screens.sort().map((s) => `- \`${s}\``), "");
writeFileSync("docs/qa/inventory.md", lines.join("\n") + "\n");
console.log(`inventory: ${api.length} endpoints, ${pages.length} pages, ${mcp.length} tools, ${screens.length} screens`);
