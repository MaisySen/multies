/**
 * Bundles the SQL files drizzle-kit writes into ./drizzle into a TypeScript module,
 * so the same migrations run on Node (better-sqlite3) and on Cloudflare D1 without a filesystem.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

function bundle(dirName: string, constName: string, outFile: string) {
  const dir = path.resolve(import.meta.dirname, "..", dirName);
  const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
  const migrations = files.map((f) => ({
    name: f.replace(/\.sql$/, ""),
    statements: readFileSync(path.join(dir, f), "utf8")
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean),
  }));
  const out = `// Generated by scripts/bundle-migrations.ts. Do not edit.\nexport const ${constName}: { name: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`;
  writeFileSync(path.resolve(import.meta.dirname, "../src/server/db", outFile), out);
  console.log(`bundled ${migrations.length} migration(s) from ${dirName}`);
}

bundle("drizzle", "MIGRATIONS", "migrations.generated.ts");
// Tools P2 (17): the separate attachment text index database (binding INDEX_DB).
bundle("drizzle-index", "INDEX_MIGRATIONS", "index-migrations.generated.ts");
