/**
 * Bundles the SQL files drizzle-kit writes into ./drizzle into a TypeScript module,
 * so the same migrations run on Node (better-sqlite3) and on Cloudflare D1 without a filesystem.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.resolve(import.meta.dirname, "../drizzle");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const migrations = files.map((f) => ({
  name: f.replace(/\.sql$/, ""),
  statements: readFileSync(path.join(dir, f), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}));
const out = `// Generated by scripts/bundle-migrations.ts. Do not edit.\nexport const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`;
writeFileSync(path.resolve(import.meta.dirname, "../src/server/db/migrations.generated.ts"), out);
console.log(`bundled ${migrations.length} migration(s)`);
